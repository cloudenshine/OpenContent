"""Shared editorial guidance for writing and independent review."""

WRITING = """表达质量要求（服从用户明确的受众、体裁和语气要求）：
先确定这篇文章在回答读者的哪个具体问题，再安排论点、解释和必要例子；不要把资料目录直接拼成正文。
用具体的人、动作、条件和结果解释抽象概念，交代为什么以及如何得出结论。术语首次出现时按受众需要解释。
像一个尊重读者的作者说话：保留判断与细节，段落自然承接，避免空泛开场、重复总结、宣传腔和机械排比。
自然表达不等于强行口语化；不要求固定句长、固定结构、每段故事或一律使用第二人称。专业体裁可以保持严谨。
不得为了亲切感虚构个人经历、采访、情绪、用户案例或效果数字。假设例子须明确标示，不能作为事实证据。
区分事实、推断和建议，在相关结论处说明必要限制，不用满篇免责声明打断阅读。
正文服务读者，不暴露内部流程字段或审稿术语；必须保留的 Claim 原句与标记仍遵守协议，通过前后文自然衔接。
交付前自行检查：读者能否说出中心意思，抽象判断是否得到解释，有没有删去也不影响意思的套话。
"""

CRITIQUE = """独立检查表达与读者收益，不因格式合规或引文存在而自动 PASS：
Voice：按项目受众和体裁检查自然程度、术语负担、段落衔接、空泛套话与作者判断。
Utility：检查是否回答具体读者问题，是否解释关键原因；操作型文章须有适用条件和可执行步骤，其他体裁不强制步骤清单。
对 Voice 和 Utility，reason 应引用短小正文片段或指出段落，解释读者受到的影响；有问题时给出具体修改方向。
缺陷明显影响理解或使用时 WARN；严重妨碍目标达成时 FAIL；PASS 也须说明正文中的具体依据。
不要凭某个词、句长、口语多少或所谓 AI 检测分数裁决。风格偏好不应成为硬性阻断，避免把所有文章改成一种声音。
若亲切叙述引入无来源的真实经历、人物引语或效果数字，同时在 Evidence 轴指出；明确标示的假设例子不当作实证。
此前审稿结论不是本次通过依据，必须检查当前正文。提出最值得先改的问题，不为展示审查力度制造问题。
"""


RESEARCH_ANALYSIS = """研究分析底稿要求：
明确要回答的核心问题与暂定判断；记录主要观察与适用范围；如有竞争解释需说明现有证据是否能够区分；如实列出关键缺口、反证或会改变判断的新事实，严禁虚构来源；阐明相对已有理解的新增增量。
"""

REVISION = """定向修订要求：
优先输出“问题位置—影响—最小建议修改”，说明改动理由。读者正文只包含成品内容，不得把执行过程说明、任务元数据、主张标记说明或审稿术语写入正文。
"""

def guidance(stage):
    if stage == "critique":
        return WRITING + "\n" + CRITIQUE + "\n核对研究分析底稿（若有）：检查正文是否保留了研究记录的适用边界、限制与反证，是否将尚未排除的竞争解释或不确定推断夸大为绝对结论。"
    if stage == "revise":
        return WRITING + "\n" + REVISION
    if stage == "draft":
        return WRITING
    if stage == "research":
        return "主张原句将进入正文：用受众能理解的完整句子表达具体判断，保留证据的条件和不确定性，避免口号与内部字段。\n" + RESEARCH_ANALYSIS
    return ""
